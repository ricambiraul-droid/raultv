// Netezire Catmull-Rom: transforma o polilinie cu putine puncte intr-o curba fina.
function smoothStroke(points, steps = 8) {
  if (points.length < 3) return points;
  const first = points[0];
  const last = points[points.length - 1];
  const closed = Math.abs(first[0] - last[0]) < 1e-9 && Math.abs(first[1] - last[1]) < 1e-9;
  const base = closed ? points.slice(0, -1) : points;
  const n = base.length;
  if (n < 3) return points;

  const at = index => {
    if (closed) return base[((index % n) + n) % n];
    return base[Math.max(0, Math.min(n - 1, index))];
  };

  const output = [];
  const segments = closed ? n : n - 1;
  for (let i = 0; i < segments; i++) {
    const p0 = at(i - 1);
    const p1 = at(i);
    const p2 = at(i + 1);
    const p3 = at(i + 2);
    for (let step = 0; step < steps; step++) {
      const t = step / steps;
      const t2 = t * t;
      const t3 = t2 * t;
      output.push([
        0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3),
        0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
      ]);
    }
  }
  output.push(closed ? output[0] : base[n - 1]);
  return output;
}

// Aplica netezirea o singura data per glifa si memoreaza rezultatul.
const smoothed = new Map();
function strokesOf(definition, key) {
  if (!definition.c) return definition.s;
  if (smoothed.has(key)) return smoothed.get(key);
  const curved = new Set(definition.c);
  const result = definition.s.map((stroke, index) => (curved.has(index) ? smoothStroke(stroke) : stroke));
  smoothed.set(key, result);
  return result;
}

function shift(stroke, dx) {
  return stroke.map(([x, y]) => [x + dx, y]);
}

