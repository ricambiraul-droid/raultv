const FALLBACK = {
  'Ä': 'A', 'À': 'A', 'Á': 'A', 'Ê': 'E', 'É': 'E', 'È': 'E',
  'Ö': 'O', 'Ó': 'O', 'Ü': 'U', 'Ú': 'U', 'Í': 'I', 'Ç': 'C', 'Ñ': 'N'
};

const TRACKING = 0.09; // spatiu intre litere, in unitati de em

function glyph(character) {
  const upper = character.toUpperCase();
  if (G[upper]) return G[upper];
  if (FALLBACK[upper] && G[FALLBACK[upper]]) return G[FALLBACK[upper]];
  return G['-'];
}

// Latimea textului in unitati de em (1 em = inaltimea majusculei).
function measure(text) {
  const characters = [...String(text)];
  if (!characters.length) return 0;
  let width = 0;
  for (const character of characters) width += glyph(character).w + TRACKING;
  return width - TRACKING;
}

// Returneaza poliliniile textului, scalate si pozitionate.
// x, y = coltul stanga-sus al casetei majusculei; size = inaltimea majusculei in pixeli.
function layout(text, x, y, size) {
  const result = [];
  let cursor = x;
  for (const character of [...String(text)]) {
    const key = character.toUpperCase();
    const definition = glyph(character);
    for (const stroke of strokesOf(definition, key)) {
      result.push(stroke.map(([px, py]) => [cursor + px * size, y + py * size]));
    }
    cursor += (definition.w + TRACKING) * size;
  }
  return result;
}

module.exports = { measure, layout, TRACKING };
